package ru.fell.notifylib.core.engine;

/** Видит ли игрок тосты. Зависит от статуса ресурспака. */
public enum DeliveryState {
    /** Пак загружен (или считаем, что загружен): показываем через боссбары. */
    READY,
    /** Пак ещё качается: тосты ждут в очереди. */
    PENDING,
    /** Игрок отказался от пака или загрузка упала: тосты идут в запасной канал. */
    FAILED
}
