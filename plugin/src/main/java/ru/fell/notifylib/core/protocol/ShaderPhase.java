package ru.fell.notifylib.core.protocol;

/** Фаза в коде тоста; ordinal и есть закодированное значение, порядок не менять. */
public enum ShaderPhase {
    /** Стоит на месте. */
    STAY,
    /** Выезжает из-за края экрана. */
    IN,
    /** Уезжает за край экрана. */
    OUT,
    /** Сдвигается на одну позицию в стопке. */
    SHIFT
}
