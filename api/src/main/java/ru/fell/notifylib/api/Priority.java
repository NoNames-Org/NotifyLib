package ru.fell.notifylib.api;

/** Порядок в очереди ожидания: сначала более высокий приоритет, при равном приоритете самый старый тост. */
public enum Priority {
    LOW,
    /** По умолчанию. */
    NORMAL,
    /** Показывается раньше тостов с меньшим приоритетом, стоящих в очереди. */
    HIGH
}
